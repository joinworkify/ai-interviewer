"use client";

import { useCallback, useEffect, useState, useSyncExternalStore } from "react";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { browserControllerDeps } from "@/lib/gemini-live/browser";
import {
  LiveInterviewController,
  type ControllerState,
  type SessionPhase,
} from "@/lib/gemini-live/controller";
import {
  INTERVIEW_LEVELS,
  MAX_ROLE_LENGTH,
  MAX_SESSION_SECONDS,
  validateLiveInterviewBody,
  type InterviewLevel,
} from "@/lib/gemini-live/interview-details";

const STATUS_LABEL: Record<SessionPhase, string> = {
  idle: "Ready",
  microphone: "Waiting for microphone permission…",
  authorizing: "Preparing a secure session…",
  connecting: "Connecting to Gemini Live…",
  active: "Interview in progress",
  closing: "Interviewer is wrapping up…",
  ended: "Interview ended",
  error: "Error",
};

const RUNNING: ReadonlySet<SessionPhase> = new Set([
  "microphone",
  "authorizing",
  "connecting",
  "active",
  "closing",
]);

function formatClock(ms: number): string {
  const total = Math.max(0, Math.floor(ms / 1000));
  return `${Math.floor(total / 60)}:${String(total % 60).padStart(2, "0")}`;
}

function downloadSession(state: ControllerState) {
  const payload = {
    note: "Practice session transcript generated by Gemini Live. Not authoritative hiring evidence.",
    details: state.details,
    startedAt: state.startedAt ? new Date(state.startedAt).toISOString() : null,
    endedAt: state.endedAt ? new Date(state.endedAt).toISOString() : null,
    outcome: state.error ?? state.notice,
    transcript: state.transcript.map(({ speaker, text, interrupted }) => ({
      speaker,
      text,
      ...(interrupted ? { interrupted: true } : {}),
    })),
  };
  const blob = new Blob([JSON.stringify(payload, null, 2)], {
    type: "application/json",
  });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `interview-session-${new Date().toISOString().slice(0, 19).replace(/:/g, "-")}.json`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function GeminiLiveInterview({ configured }: { configured: boolean }) {
  // Constructing touches no browser APIs; resources are created on Start.
  const [controller] = useState(() => new LiveInterviewController(browserControllerDeps));
  const state = useSyncExternalStore(
    controller.subscribe,
    controller.getSnapshot,
    controller.getSnapshot,
  );

  const [role, setRole] = useState("");
  const [level, setLevel] = useState<InterviewLevel>("mid");
  const [techstack, setTechstack] = useState("");
  const [formError, setFormError] = useState<string | null>(null);
  const [now, setNow] = useState(() => Date.now());

  // Unmount / navigation: stop mic, close socket and audio.
  useEffect(() => () => controller.dispose(), [controller]);

  const running = RUNNING.has(state.phase);
  const timing = state.phase === "active" || state.phase === "closing";
  useEffect(() => {
    if (!timing) return;
    setNow(Date.now());
    const id = setInterval(() => setNow(Date.now()), 500);
    return () => clearInterval(id);
  }, [timing]);

  const start = useCallback(() => {
    const result = validateLiveInterviewBody({ role, level, techstack });
    if (!result.ok) {
      setFormError(result.errors.join(" "));
      return;
    }
    setFormError(null);
    void controller.start(result.data);
  }, [controller, level, role, techstack]);

  const elapsedMs =
    state.startedAt === null
      ? 0
      : (timing ? now : (state.endedAt ?? now)) - state.startedAt;

  return (
    <div className="flex flex-col gap-6">
      <div
        role="note"
        className="rounded-md border border-yellow-500/50 bg-yellow-500/10 p-4 text-sm flex flex-col gap-1"
      >
        <p className="font-semibold">Prototype</p>
        <ul className="list-disc pl-5 flex flex-col gap-1">
          <li>
            Audio streams directly from your browser to Google Gemini Live.
            Usage is billed to this app&apos;s Google API key; direct Google
            costs apply.
          </li>
          <li>
            Sessions are capped at {MAX_SESSION_SECONDS / 60} minutes. Nothing is
            recorded or saved: the transcript exists only in this tab until you
            leave or start again.
          </li>
          <li>
            Transcripts are machine-generated and may be inaccurate. This is
            practice only, not authoritative hiring evidence. No scoring or
            feedback is produced.
          </li>
          <li>Headphones are recommended to avoid echo.</li>
        </ul>
      </div>

      <form
        className="grid gap-4 sm:grid-cols-3"
        onSubmit={(e) => {
          e.preventDefault();
          // Only the Start button (or Enter in a field) may start a session.
          const submitter = (e.nativeEvent as SubmitEvent).submitter;
          if (submitter && submitter.getAttribute("data-action") !== "start") return;
          // Read live state, not this render's closure.
          if (RUNNING.has(controller.getSnapshot().phase)) return;
          start();
        }}
      >
        <div className="flex flex-col gap-2">
          <Label htmlFor="gl-role">Role</Label>
          <Input
            id="gl-role"
            value={role}
            onChange={(e) => setRole(e.target.value)}
            placeholder="e.g. Backend Engineer"
            maxLength={MAX_ROLE_LENGTH}
            required
            disabled={running}
          />
        </div>
        <div className="flex flex-col gap-2">
          <Label htmlFor="gl-level">Experience level</Label>
          <select
            id="gl-level"
            value={level}
            onChange={(e) => setLevel(e.target.value as InterviewLevel)}
            disabled={running}
            className="flex h-9 w-full rounded-md border border-input bg-transparent px-3 py-1 text-sm shadow-sm disabled:cursor-not-allowed disabled:opacity-50"
          >
            {INTERVIEW_LEVELS.map((l) => (
              <option key={l.value} value={l.value}>
                {l.label}
              </option>
            ))}
          </select>
        </div>
        <div className="flex flex-col gap-2">
          <Label htmlFor="gl-stack">Tech stack (comma-separated)</Label>
          <Input
            id="gl-stack"
            value={techstack}
            onChange={(e) => setTechstack(e.target.value)}
            placeholder="e.g. Go, PostgreSQL, Kubernetes"
            maxLength={400}
            required
            disabled={running}
          />
        </div>

        <div className="sm:col-span-3 flex flex-wrap items-center gap-3">
          {/*
            Distinct keys: React must never morph the End <button> into the
            submit button. A user click commits the re-render in a microtask
            before the button's default action runs, so a reused node would
            already be type="submit" and restart the interview.
          */}
          {running ? (
            <Button
              key="end"
              type="button"
              variant="destructive"
              data-action="end"
              onClick={(e) => {
                e.preventDefault(); // canceled click => no form activation
                controller.end();
              }}
            >
              End interview
            </Button>
          ) : (
            <Button key="start" type="submit" data-action="start" disabled={!configured}>
              {state.phase === "idle" ? "Start interview" : "Start again"}
            </Button>
          )}
          <span className="text-sm text-muted-foreground" aria-live="polite">
            {STATUS_LABEL[state.phase]}
            {state.phase === "active" &&
              (state.interviewerSpeaking ? " · interviewer speaking" : " · listening")}
          </span>
          {state.startedAt !== null && (
            <span className="text-sm font-mono tabular-nums" aria-label="Elapsed time">
              {formatClock(elapsedMs)} / {formatClock(MAX_SESSION_SECONDS * 1000)}
            </span>
          )}
        </div>
      </form>

      {formError && (
        <p role="alert" className="text-sm text-destructive">
          {formError}
        </p>
      )}
      {state.error && (
        <div
          role="alert"
          className="rounded-md border border-destructive/50 bg-destructive/10 p-3 text-sm text-destructive"
        >
          {state.error}
        </div>
      )}
      {state.notice && !state.error && (
        <p className="text-sm text-muted-foreground" aria-live="polite">
          {state.notice}
        </p>
      )}

      {state.transcript.length > 0 && (
        <section className="flex flex-col gap-2">
          <div className="flex items-center justify-between gap-3">
            <h2 className="font-semibold">Transcript (this session only)</h2>
            {!running && (
              <Button
                type="button"
                variant="outline"
                size="sm"
                onClick={() => downloadSession(state)}
              >
                Download session JSON
              </Button>
            )}
          </div>
          <div className="max-h-96 overflow-y-auto rounded-md border p-3 text-sm flex flex-col gap-2">
            {state.transcript.map((entry) => (
              <p
                key={entry.id}
                className={entry.final ? undefined : "text-muted-foreground italic"}
              >
                <span className="font-semibold">
                  {entry.speaker === "interviewer" ? "Interviewer" : "You"}:
                </span>{" "}
                {entry.text.trim()}
                {entry.interrupted && (
                  <span className="text-xs text-muted-foreground"> (interrupted)</span>
                )}
              </p>
            ))}
          </div>
        </section>
      )}
    </div>
  );
}
